"use strict";

const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const test = require("node:test");
const {
  applyApplicantCustomerAction,
  applyApplicantDecisions,
  catalogue,
  evaluateApplicantJourney,
  startApplicantFixture,
} = require("../server/applicantJourneyLab");
const { buildCustomerActionV2 } = require("../../ubo-control-ui/UboApplicantJourneyV2");

const AT = "2026-09-09T12:00:00.000Z";

function current(session) { return session.snapshots.at(-1); }
function findAction(session, actionType) {
  for (const bundle of current(session).journey.customerWorkBundles) {
    const action = bundle.permittedSemanticActions.find((item) => item.actionType === actionType && item.executable);
    if (action) return { bundle, action };
  }
  throw new Error(`No executable ${actionType}`);
}
function action(session, actionType, payload) {
  const selected = findAction(session, actionType);
  return buildCustomerActionV2({
    journey: current(session).journey,
    ...selected,
    actorContext: session.actorContext,
    content: session.content,
    payload,
    submittedAt: AT,
    informationAsAtDate: AT,
  });
}
function confirmPayload(session) {
  const { bundle } = findAction(session, "CONFIRM_ESTABLISHED_INFORMATION");
  return {
    confirmation: "CONFIRMED",
    establishedRelationshipIds: bundle.knownInformation.relationships.map(({ relationshipId }) => relationshipId),
    establishedClaimIds: bundle.knownInformation.relationships.flatMap(({ supportingClaimIds }) => supportingClaimIds),
  };
}

test("catalogue exposes AJV2-01 through AJV2-15 and each is generated by actual contracts", () => {
  assert.deepEqual(catalogue().fixtures.map(({ fixtureId }) => fixtureId),
    Array.from({ length: 15 }, (_, index) => `AJV2-${String(index + 1).padStart(2, "0")}`));
  catalogue().fixtures.forEach(({ fixtureId }) => {
    const session = startApplicantFixture({ fixtureId });
    assert.equal(current(session).snapshot.snapshotSchemaVersion, "ubo-decision-snapshot-v2", fixtureId);
    assert.equal(current(session).plan.contractVersion, "ubo-resolution-plan-v2", fixtureId);
    assert.equal(current(session).journey.contractVersion, "ubo-journey-projection-v2", fixtureId);
    assert.deepEqual(session.operationHistory, ["INTAKE", "EXPLICIT_FIXTURE_DECISIONS", "EVALUATE"], fixtureId);
  });
});

test("confirmation records the non-replacement principle and exact SATISFIED/OPEN R08 state", () => {
  for (const [fixtureId, evidenceState] of [["AJV2-01", "SATISFIED"], ["AJV2-02", "OPEN"]]) {
    let session = startApplicantFixture({ fixtureId });
    const beforeClaims = session.pendingDecisionTargets.candidateClaims.length;
    session = applyApplicantCustomerAction({
      session,
      customerAction: action(session, "CONFIRM_ESTABLISHED_INFORMATION", confirmPayload(session)),
      operationId: `${fixtureId}:confirmation`,
    });
    const confirmation = session.latestCustomerActionResult.customerConfirmation;
    assert.equal(confirmation.confirmationDoesNotReplaceIndependentEvidence, true);
    assert.equal(confirmation.independentEvidenceRequirementState, evidenceState);
    assert.equal(session.latestCustomerActionResult.customerOriginatedCandidateFacts.length, 0);
    assert.equal(session.pendingDecisionTargets.candidateClaims.length, beforeClaims);
    assert.equal(session.latestCustomerActionResult.hiddenEvaluationPerformed, false);
  }
});

test("customer input, explicit decisions and re-evaluation are three separate operations with immutable Snapshot A", () => {
  let session = startApplicantFixture({ fixtureId: "AJV2-04" });
  const first = structuredClone(current(session).snapshot);
  const { bundle } = findAction(session, "SUBMIT_STRUCTURED_RELATIONSHIP");
  const targetEntityId = bundle.canonicalSubject.entityId || bundle.canonicalSubject.entityIds[0];
  const customerAction = action(session, "SUBMIT_STRUCTURED_RELATIONSHIP", {
    relationships: [{
      localPartyKey: "foreign-owner-1",
      owner: { localPartyKey: "foreign-owner-1", name: "Foreign Owner Example", entityType: "LEGAL_ENTITY", jurisdiction: "NL", externalIdentifiers: [{ namespace: "CUSTOMER_PROVIDED_REGISTRATION", value: "NL-TEST-01" }] },
      targetEntityId,
      concept: "SHARE_OWNERSHIP",
      direction: "OWNER_TO_TARGET",
      relationshipType: "ECONOMIC_OWNERSHIP",
      measurement: { type: "RANGE", lowerBound: 0, upperBound: 10, lowerInclusive: false, upperInclusive: true },
      assertionState: "CURRENT",
      asAtDate: AT,
    }],
  });
  session = applyApplicantCustomerAction({ session, customerAction, operationId: "AJV2-04:apply" });
  assert.equal(session.snapshots.length, 1);
  assert.equal(session.pendingDecisionTargets.candidateClaims.length, 1);
  assert.equal(session.latestCustomerActionResult.customerOriginatedCandidateFacts[0].measurement.type, "RANGE");
  assert.equal(session.latestCustomerActionResult.hiddenEvaluationPerformed, false);
  assert.throws(() => evaluateApplicantJourney({ session }), /Explicit identity and claim decisions/);
  session = applyApplicantDecisions({ session, recordedAt: "2026-09-09T12:01:00.000Z" });
  assert.equal(session.pendingDecisionTargets.candidateClaims.length, 0);
  session = evaluateApplicantJourney({ session, evaluationTime: "2026-09-09T12:02:00.000Z" });
  assert.equal(session.snapshots.length, 2);
  assert.notEqual(current(session).snapshot.snapshotId, first.snapshotId);
  assert.deepEqual(session.snapshots[0].snapshot, first);
  assert.deepEqual(session.operationHistory.slice(-3), ["APPLY_CUSTOMER_INPUT", "APPLY_EXPLICIT_DECISIONS", "EVALUATE"]);
});

test("structured ownership preserves exact, range and unknown candidate values", () => {
  const measurements = [
    { type: "EXACT", value: 10 },
    { type: "RANGE", lowerBound: 0, upperBound: 10, lowerInclusive: false, upperInclusive: true },
    { type: "UNKNOWN", reason: "Awaiting the current register" },
  ];
  measurements.forEach((measurement, index) => {
    let session = startApplicantFixture({ fixtureId: "AJV2-04" });
    const { bundle } = findAction(session, "SUBMIT_STRUCTURED_RELATIONSHIP");
    const targetEntityId = bundle.canonicalSubject.entityId || bundle.canonicalSubject.entityIds[0];
    session = applyApplicantCustomerAction({
      session,
      customerAction: action(session, "SUBMIT_STRUCTURED_RELATIONSHIP", {
        relationships: [{
          localPartyKey: `measurement-owner-${index}`,
          owner: { localPartyKey: `measurement-owner-${index}`, name: `Owner ${index}`, entityType: "NATURAL_PERSON", externalIdentifiers: [] },
          targetEntityId,
          concept: "SHARE_OWNERSHIP",
          direction: "OWNER_TO_TARGET",
          relationshipType: "ECONOMIC_OWNERSHIP",
          measurement,
          assertionState: "CURRENT",
          asAtDate: AT,
        }],
      }),
      operationId: `AJV2-04:measurement:${index}`,
    });
    assert.deepEqual(session.latestCustomerActionResult.customerOriginatedCandidateFacts[0].measurement, measurement);
    assert.equal(session.latestCustomerActionResult.requiredNextOperation, "APPLY_DECISIONS");
  });
});

test("external Evidence stops at a byte-free handoff and leaves work open", () => {
  let session = startApplicantFixture({ fixtureId: "AJV2-05" });
  const { bundle } = findAction(session, "REQUEST_EXTERNAL_EVIDENCE");
  session = applyApplicantCustomerAction({
    session,
    customerAction: action(session, "REQUEST_EXTERNAL_EVIDENCE", {
      requestCorrelationId: "AJV2-05:evidence",
      evidenceCategories: bundle.evidenceHandoff.semanticEvidenceCategories,
      requestedConcepts: bundle.evidenceHandoff.requestedConcepts,
      informationAsAtDate: AT,
    }),
    operationId: "AJV2-05:apply",
  });
  const handoff = session.latestCustomerActionResult.externalEvidenceHandoff;
  assert.equal(handoff.contractVersion, "ubo-external-evidence-handoff-v1");
  assert.equal(handoff.executionConnected, false);
  assert.equal(handoff.createsEvidenceArtifact, false);
  assert.equal(session.latestCustomerActionResult.needSatisfiedByReceipt, false);
  assert.doesNotMatch(JSON.stringify(handoff), /base64|blob:|filesystem|artifactId|filePath/i);
});

test("delegation prepares only a host handoff and grants no authority or completion", () => {
  let session = startApplicantFixture({ fixtureId: "AJV2-06" });
  session = applyApplicantCustomerAction({
    session,
    customerAction: action(session, "DELEGATE_CUSTOMER_WORK", {
      delegateReference: "Group secretary",
      delegateCapacity: "COMPANY_SECRETARY",
      requestedWorkScope: "Provide the planned ownership information",
      informationAsAtExpectation: AT,
      correlationId: "AJV2-06:delegate",
    }),
    operationId: "AJV2-06:apply",
  });
  const handoff = session.latestCustomerActionResult.delegationHandoff;
  assert.equal(handoff.contractVersion, "ubo-customer-work-delegation-v1");
  assert.equal(handoff.executionOwner, "HOST");
  assert.equal(handoff.authorizationGranted, false);
  assert.equal(handoff.workCompleted, false);
});

